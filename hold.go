// holdsTable is where holds are kept.
const holdsTable = "wallet_holds"

// HoldStatus is where a hold stands. A hold is placed held and settles once,
// into exactly one of the other three.
type HoldStatus string

// The situations of a hold.
const (
	// HoldHeld sets money aside: the balance has not moved, and no other
	// withdrawal reaches the amount.
	HoldHeld HoldStatus = "held"
	// HoldCaptured took the money: a withdrawal was written under the
	// operation the hold names.
	HoldCaptured HoldStatus = "captured"
	// HoldReleased gave the amount back to what the wallet may spend, by a
	// decision somebody made.
	HoldReleased HoldStatus = "released"
	// HoldExpired gave it back because the time the hold was placed for ended.
	HoldExpired HoldStatus = "expired"
)

// Hold is money a wallet promised and has not yet paid.
//
// It is the reservation a caller places before work whose price is known and
// whose outcome is not: the amount stops being spendable at once, under the
// same statement guard every withdrawal answers to, and then the work either
// happened -- the hold is captured into a real withdrawal -- or did not, and the
// hold is released. Nothing moves the balance until the capture, so a hold that
// is released leaves no entry in the ledger and nothing to reverse.
//
// The amount held stays on the wallet's Held column while the hold is open,
// which is what the withdrawal guard reads. This row is the record of why.
type Hold struct {
	model.Model

	// ID is the identifier, generated by the application.
	ID string `db:"id"`

	// TenantID is the customer the row belongs to, written from the Grant.
	TenantID string `db:"tenant_id"`

	// WalletID is the wallet the money is held on.
	WalletID string `db:"wallet_id"`

	// IdempotencyKey is the caller's name for the request that placed it. The
	// same key twice places one hold.
	IdempotencyKey string `db:"idempotency_key"`

	// Amount is what is held, in the wallet's minor units.
	Amount Amount `db:"amount"`

	// Status is where the hold stands.
	Status HoldStatus `db:"status"`

	// ExpiresAt is when the hold stops holding, and nil for one that holds
	// until somebody captures or releases it. A hold past it is not captured;
	// ReleaseExpired gives it back.
	ExpiresAt *time.Time `db:"expires_at"`

	// OperationID is the withdrawal a capture wrote, and empty otherwise.
	OperationID string `db:"operation_id"`

	// Reason is why a hold was released, and empty while it holds or once it
	// was captured.
	Reason string `db:"reason"`

	// Meta is what the application attached when it placed the hold.
	Meta Meta `db:"meta"`

	// CreatedAt is when the hold was placed, in UTC.
	CreatedAt time.Time `db:"created_at"`

	// UpdatedAt is when it last changed, in UTC.
	UpdatedAt time.Time `db:"updated_at"`
}

// holdTable is the holds table, and Holds is the query that starts on it.
var holdTable = model.NewTable(model.TableSpec{
	Name:      holdsTable,
	New:       func() model.Entity { return new(Hold) },
	ManualKey: true,
})

// Open reports whether the hold still sets money aside.
func (h Hold) Open() bool { return h.Status == HoldHeld }

// ExpiredAt reports whether the hold's time is over at the given moment.
func (h Hold) ExpiredAt(now time.Time) bool {
	return h.ExpiresAt != nil && !h.ExpiresAt.After(now)
}

// HoldRequest is what setting money aside takes.
type HoldRequest struct {
	// IdempotencyKey is the caller's name for this request. The same key twice
	// places one hold, and the same key for another wallet or amount is
	// ErrOperationConflict.
	IdempotencyKey string
	// WalletID is the wallet the money is held on.
	WalletID string
	// Amount is the decimal to hold, written at the wallet's own scale.
	Amount string
	// ExpiresAt is when the hold stops holding. The zero time holds until
	// somebody captures or releases it.
	ExpiresAt time.Time
	// Meta is what the application attaches to the hold.
	Meta Meta
}

// Validate reports the errors per field.
func (r HoldRequest) Validate() validation.Errors {
	return validateMovement(r.IdempotencyKey, r.WalletID, r.Amount, r.Meta)
}

// CaptureRequest is what turning a hold into a withdrawal takes.
type CaptureRequest struct {
	// IdempotencyKey is the capture's own key, and never the hold's.
	IdempotencyKey string
	// HoldID is the hold to capture. The whole amount is captured.
	HoldID string
	// Meta is what the application attaches to the withdrawal.
	Meta Meta
}

// Validate reports the errors per field.
func (r CaptureRequest) Validate() validation.Errors {
	e := validation.Errors{}
	validation.Required(e, "idempotency_key", r.IdempotencyKey)
	validation.MaxLen(e, "idempotency_key", r.IdempotencyKey, maxIdempotencyKeyLen)
	validation.Required(e, "hold_id", r.HoldID)
	validation.MaxLen(e, "hold_id", r.HoldID, maxIdentifierLen)
	checkMeta(e, "meta", r.Meta)
	return e
}

// ReleaseRequest is what giving a hold back takes.
type ReleaseRequest struct {
	// HoldID is the hold to release.
	HoldID string
	// Reason is what the release is recorded as. It is required, because a
	// hold given back with no reason is a promise nobody can account for.
	Reason string
}

// Validate reports the errors per field.
func (r ReleaseRequest) Validate() validation.Errors {
	e := validation.Errors{}
	validation.Required(e, "hold_id", r.HoldID)
	validation.MaxLen(e, "hold_id", r.HoldID, maxIdentifierLen)
	validation.Required(e, "reason", r.Reason)
	validation.MaxLen(e, "reason", r.Reason, maxReasonLen)
	return e
}

// Hold sets money aside on a wallet without moving its balance.
//
// What may be held is what a withdrawal could take: the balance and the credit
// limit, less what other holds already set aside. The check is the predicate of
// the statement that raises the held column, so two holds racing for the last
// of the money cannot both be placed -- the second statement matches no row and
// is refused with ErrInsufficientFunds.
func (s *WalletService) Hold(ctx context.Context, actor security.Subject, in HoldRequest) (*Hold, error) {
	if errs := in.Validate(); errs.Any() {
		return nil, errs
	}
	g, err := security.Authorize(ctx, s.policy, actor, WalletHold, Wallet{})
	if err != nil {
		return nil, err
	}
	source, err := Wallets(s.db).WhereKey(in.WalletID).First(ctx, g)
	if err != nil {
		return nil, err
	}
	if source == nil {
		return nil, ErrNotFound
	}
	if _, err := security.Authorize(ctx, s.policy, actor, WalletHold, *source); err != nil {
		return nil, err
	}
	amount, err := positiveAmount(in.Amount, source.DecimalPlaces)
	if err != nil {
		return nil, err
	}
	if existing, err := s.heldUnder(ctx, g, in.IdempotencyKey, source.ID, amount); err != nil || existing != nil {
		return existing, err
	}
	now := time.Now().UTC()
	if !in.ExpiresAt.IsZero() && !in.ExpiresAt.After(now) {
		return nil, validation.Errors{"expires_at": {"the hold would expire before it is placed"}}
	}

	id, err := data.NewID()
	if err != nil {
		return nil, err
	}
	h, err := Holds(s.db).New()
	if err != nil {
		return nil, err
	}
	h.ID, h.TenantID, h.WalletID = id, data.Tenant(g), source.ID
	h.IdempotencyKey, h.Amount, h.Status, h.Meta = in.IdempotencyKey, amount, HoldHeld, in.Meta
	if !in.ExpiresAt.IsZero() {
		at := in.ExpiresAt.UTC()
		h.ExpiresAt = &at
	}
	h.CreatedAt, h.UpdatedAt = now, now

	err = database.TransactionAt(ctx, s.db, sql.LevelReadCommitted, func(ctx context.Context) error {
		placed, err := s.setAside(ctx, g, source, amount)
		if err != nil {
			return err
		}
		if !placed {
			return s.whyNotHeld(ctx, g, source.ID)
		}
		_, err = h.Save(ctx, g)
		return err
	})
	if err != nil {
		// Two requests under one key racing: the unique index kept one, and
		// the loser answers with the winner's hold -- or with a conflict, when
		// the winner asked for something else.
		if existing, ferr := s.heldUnder(ctx, g, in.IdempotencyKey, source.ID, amount); ferr != nil || existing != nil {
			if ferr != nil {
				return nil, ferr
			}
			return existing, nil
		}
		return nil, err
	}
	return h, nil
}

// heldUnder answers the hold a key already placed, nil where it placed none,
// and ErrOperationConflict where it placed a different one.
func (s *WalletService) heldUnder(ctx context.Context, g security.Grant, key, walletID string, amount Amount) (*Hold, error) {
	existing, err := Holds(s.db).Where("idempotency_key", key).First(ctx, g)
	if err != nil || existing == nil {
		return nil, err
	}
	if existing.WalletID != walletID || existing.Amount != amount {
		return nil, ErrOperationConflict
	}
	return existing, nil
}

// Capture turns a hold into the withdrawal it promised, for its whole amount.
//
// The withdrawal and the hold settling are one transaction: the money leaves,
// the held column comes down by the same amount and the hold records the
// operation, or none of the three happens. The same key twice captures once,
// and a hold that was already released or expired is ErrHoldNotHeld.
func (s *WalletService) Capture(ctx context.Context, actor security.Subject, in CaptureRequest) (Receipt, error) {
	if errs := in.Validate(); errs.Any() {
		return Receipt{}, errs
	}
	g, err := security.Authorize(ctx, s.policy, actor, WalletCapture, Wallet{})
	if err != nil {
		return Receipt{}, err
	}
	h, err := Holds(s.db).WhereKey(in.HoldID).First(ctx, g)
	if err != nil {
		return Receipt{}, err
	}
	if h == nil {
		return Receipt{}, ErrNotFound
	}
	source, err := s.holdWallet(ctx, g, actor, WalletCapture, h)
	if err != nil {
		return Receipt{}, err
	}
	asked := askedMovement(source.ID, EntryWithdraw, h.Amount, false)
	if receipt, found, err := s.replay(ctx, g, in.IdempotencyKey, OperationWithdraw, source.ID, asked); err != nil || found {
		return receipt, err
	}
	if !h.Open() {
		return Receipt{}, ErrHoldNotHeld
	}
	if h.ExpiredAt(time.Now()) {
		return Receipt{}, ErrHoldExpired
	}
	meta := Meta{}
	for k, v := range in.Meta {
		meta[k] = v
	}
	meta["hold"] = h.ID
	return s.commit(ctx, g, operation{
		key:   in.IdempotencyKey,
		kind:  OperationWithdraw,
		meta:  meta,
		owner: source.ID,
		asked: asked,
		hold:  h.ID,
	}, []movement{{wallet: source, kind: EntryWithdraw, amount: h.Amount, fromHold: true}})
}

// Release gives a hold back: the amount is spendable again and nothing is
// written to the ledger, because nothing moved. A hold already released or
// expired answers with itself, since what was asked for is already true; a
// captured one is ErrHoldNotHeld, because its money is gone.
func (s *WalletService) Release(ctx context.Context, actor security.Subject, in ReleaseRequest) (*Hold, error) {
	if errs := in.Validate(); errs.Any() {
		return nil, errs
	}
	g, err := security.Authorize(ctx, s.policy, actor, WalletRelease, Wallet{})
	if err != nil {
		return nil, err
	}
	h, err := Holds(s.db).WhereKey(in.HoldID).First(ctx, g)
	if err != nil {
		return nil, err
	}
	if h == nil {
		return nil, ErrNotFound
	}
	if _, err := s.holdWallet(ctx, g, actor, WalletRelease, h); err != nil {
		return nil, err
	}
	return s.giveBack(ctx, g, h, HoldReleased, in.Reason)
}

// ReleaseExpired gives back the open holds whose time ended before a moment,
// at most limit of them, and answers how many it gave back. It is the sweep an
// application schedules; a hold past its time is never captured whether or not
// the sweep ran.
func (s *WalletService) ReleaseExpired(ctx context.Context, actor security.Subject, before time.Time, limit int) (int, error) {
	g, err := security.Authorize(ctx, s.policy, actor, WalletExpire, Wallet{})
	if err != nil {
		return 0, err
	}
	expired, err := Holds(s.db).Where("status", string(HoldHeld)).Where("expires_at", "<=", before.UTC()).
		OrderBy("expires_at").Limit(boundedLimit(limit)).Get(ctx, g)
	if err != nil {
		return 0, err
	}
	n := 0
	for _, h := range expired {
		source, err := Wallets(s.db).WhereKey(h.WalletID).First(ctx, g)
		if err != nil {
			return n, err
		}
		if source == nil {
			continue
		}
		if _, err := security.Authorize(ctx, s.policy, actor, WalletExpire, *source); err != nil {
			return n, err
		}
		if _, err := s.giveBack(ctx, g, h, HoldExpired, "expired"); err != nil {
			return n, err
		}
		n++
	}
	return n, nil
}

// HoldsOf lists one wallet's holds in a situation, the newest first; the empty
// status lists every one.
func (s *WalletService) HoldsOf(ctx context.Context, actor security.Subject, walletID string, status HoldStatus, limit int) ([]*Hold, error) {
	g, err := security.Authorize(ctx, s.policy, actor, WalletView, Wallet{})
	if err != nil {
		return nil, err
	}
	source, err := Wallets(s.db).WhereKey(walletID).First(ctx, g)
	if err != nil {
		return nil, err
	}
	if source == nil {
		return nil, ErrNotFound
	}
	if _, err := security.Authorize(ctx, s.policy, actor, WalletView, *source); err != nil {
		return nil, err
	}
	q := Holds(s.db).Where("wallet_id", source.ID)
	if status != "" {
		q = q.Where("status", string(status))
	}
	return q.OrderByDesc("created_at").Limit(boundedLimit(limit)).Get(ctx, g)
}

// holdWallet loads the wallet a hold is on and asks the policy about it: what
// may be done to a hold is what may be done to its money.
func (s *WalletService) holdWallet(ctx context.Context, g security.Grant, actor security.Subject, a security.Action, h *Hold) (*Wallet, error) {
	source, err := Wallets(s.db).WhereKey(h.WalletID).First(ctx, g)
	if err != nil {
		return nil, err
	}
	if source == nil {
		return nil, ErrNotFound
	}
	if _, err := security.Authorize(ctx, s.policy, actor, a, *source); err != nil {
		return nil, err
	}
	return source, nil
}

// giveBack settles an open hold without taking its money: the hold row moves
// to its final situation and the held column comes down, in one transaction.
func (s *WalletService) giveBack(ctx context.Context, g security.Grant, h *Hold, to HoldStatus, reason string) (*Hold, error) {
	switch h.Status {
	case HoldReleased, HoldExpired:
		return h, nil
	case HoldCaptured:
		return nil, ErrHoldNotHeld
	}
	now := time.Now().UTC()
	err := database.TransactionAt(ctx, s.db, sql.LevelReadCommitted, func(ctx context.Context) error {
		n, err := Holds(s.db).Where("id", h.ID).Where("status", string(HoldHeld)).
			Update(ctx, g, map[string]any{"status": string(to), "reason": reason, "updated_at": now})
		if err != nil {
			return err
		}
		if n != 1 {
			return ErrHoldNotHeld
		}
		returned, err := s.takeBack(ctx, g, &Wallet{ID: h.WalletID}, h.Amount)
		if err != nil {
			return err
		}
		if !returned {
			return fmt.Errorf("wallet: hold %s was open and its wallet holds less than it: %w", h.ID, ErrHoldNotHeld)
		}
		return nil
	})
	if err != nil {
		// Somebody settled it first: what it is now is the answer.
		if after, ferr := Holds(s.db).WhereKey(h.ID).First(ctx, g); ferr == nil && after != nil && after.Status != HoldHeld {
			if after.Status == HoldCaptured {
				return nil, ErrHoldNotHeld
			}
			return after, nil
		}
		return nil, err
	}
	return Holds(s.db).WhereKey(h.ID).First(ctx, g)
}

// captureHold marks a hold captured under the operation that took its money,
// inside the operation's transaction. A hold that stopped holding matches no
// row and the whole operation rolls back.
func (s *WalletService) captureHold(ctx context.Context, g security.Grant, holdID, operationID string) error {
	n, err := Holds(s.db).Where("id", holdID).Where("status", string(HoldHeld)).
		Update(ctx, g, map[string]any{"status": string(HoldCaptured), "operation_id": operationID, "updated_at": time.Now().UTC()})
	if err != nil {
		return err
	}
	if n != 1 {
		return ErrHoldNotHeld
	}
	return nil
}

// setAside raises a wallet's held column by an amount, when what the wallet may
// spend covers it at the instant of the write. The statement is moveStatement's,
// the one place a wallets row is written.
func (s *WalletService) setAside(ctx context.Context, g security.Grant, source *Wallet, amount Amount) (bool, error) {
	statement, bindings := moveStatement(movement{wallet: source, amount: amount, setAside: true}, data.Tenant(g), s.db.Dialect())
	_, ok, err := s.moving(ctx, statement, bindings)
	return ok, err
}

// takeBack lowers a wallet's held column by an amount that a hold had set
// aside.
func (s *WalletService) takeBack(ctx context.Context, g security.Grant, source *Wallet, amount Amount) (bool, error) {
	statement, bindings := moveStatement(movement{wallet: source, amount: amount, takeBack: true}, data.Tenant(g), s.db.Dialect())
	_, ok, err := s.moving(ctx, statement, bindings)
	return ok, err
}

// whyNotHeld says which condition refused a hold, after the statement decided.
func (s *WalletService) whyNotHeld(ctx context.Context, g security.Grant, walletID string) error {
	after, err := Wallets(s.db).WhereKey(walletID).First(ctx, g)
	if err != nil {
		return err
	}
	switch {
	case after == nil:
		return ErrNotFound
	case bool(after.Frozen):
		return ErrWalletFrozen
	case bool(after.Closed):
		return ErrWalletClosed
	case after.Balance == 0 && after.CreditLimit == 0 && after.Held == 0:
		return fmt.Errorf("%w: %w", ErrInsufficientFunds, ErrBalanceEmpty)
	}
	return ErrInsufficientFunds
}
